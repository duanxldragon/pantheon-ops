import { createHash } from 'node:crypto';
import { copyFileSync, lstatSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = process.cwd();
const candidateRelative = '.local/manual-preview-20261116/overlay-history-continuation-final-c04-ui-locale-checkpoint';
const candidate = resolve(root, candidateRelative);
const evidence = dirname(fileURLToPath(import.meta.url));
const locales = ['zh-CN', 'en-US', 'ja-JP', 'ko-KR', 'fr-FR'];
const businessPrefix = 'frontend/src/modules/business/';
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const read = (base, path) => readFileSync(resolve(base, path));
const requireRegular = (base, path) => {
  if (!lstatSync(resolve(base, path)).isFile()) throw new Error(`Expected regular file: ${path}`);
};
const canonicalPaths = (base) => {
  const paths = [];
  const visit = (relative) => {
    for (const entry of readdirSync(resolve(base, relative), { withFileTypes: true })) {
      const path = `${relative}/${entry.name}`;
      if (entry.isSymbolicLink()) throw new Error(`Unexpected link: ${path}`);
      if (entry.isDirectory()) visit(path);
      else if (entry.isFile() && locales.some((locale) => entry.name === `${locale}.json`)) paths.push(path);
    }
  };
  visit(businessPrefix.slice(0, -1));
  return paths.sort();
};

const receipt = {
  taskId: '2026-11-16-ops-k8s-service-mutations', owner: 'c04_k8s_service_ui_executor',
  scope: 'Copy only five generated business locales from the official locale checkpoint; not the final C01/appProtocol revision.',
  root, candidate, startedUTC: new Date().toISOString(), status: 'in-progress',
  canonicalBefore: [], originals: [], copies: [], canonicalAfter: [],
  testsExecuted: false, renderedEvidenceInspected: false,
};
try {
  // Complete inventory, byte and build-report checks before touching live files.
  const livePaths = canonicalPaths(root);
  const candidatePaths = canonicalPaths(candidate);
  if (JSON.stringify(livePaths) !== JSON.stringify(candidatePaths)) throw new Error('Canonical locale inventories differ');
  const reportPath = '.business-overlay-report.json';
  const reportBytes = read(candidate, reportPath);
  const report = JSON.parse(reportBytes.toString('utf8'));
  const owned = new Map(report.ownedFiles.map((row) => [row.path, row.sha256]));
  const liveLock = read(root, 'foundation-release.lock.json');
  const candidateLock = read(candidate, 'foundation-release.lock.json');
  if (!liveLock.equals(candidateLock)) throw new Error('Live and official-candidate foundation locks differ');
  receipt.foundationLockSHA256 = sha256(liveLock);
  receipt.baseCommit = report.baseCommit;
  receipt.overlayReportSHA256 = sha256(reportBytes);
  const upstreamReceiptRelative = '.harness/evidence/2026-11-17-ops-history-audit/continuation-rebuild-cache-c04-ui-locale-checkpoint-verification.json';
  const upstreamBytes = read(root, upstreamReceiptRelative);
  const upstream = JSON.parse(upstreamBytes.toString('utf8'));
  const expectedChecks = ['official-rebuild-final-c04-ui-locale-checkpoint', 'staged-overlay-final-c04-ui-locale-checkpoint', 'staged-drift-official-cache-final-c04-ui-locale-checkpoint'];
  if (expectedChecks.some((name) => !upstream.some((row) => row.name === name && row.exitCode === 0 && row.status === 'passed'))) {
    throw new Error('Required official checkpoint receipts are not all passed');
  }
  receipt.upstreamVerification = { path: upstreamReceiptRelative, sha256: sha256(upstreamBytes), checks: expectedChecks };
  for (const path of livePaths) {
    const liveBytes = read(root, path), candidateBytes = read(candidate, path);
    const liveHash = sha256(liveBytes), candidateHash = sha256(candidateBytes);
    if (!liveBytes.equals(candidateBytes) || owned.get(path) !== candidateHash) throw new Error(`Canonical byte/report mismatch: ${path}`);
    JSON.parse(liveBytes.toString('utf8'));
    receipt.canonicalBefore.push({ path, bytes: liveBytes.length, liveSHA256: liveHash, candidateSHA256: candidateHash, reportSHA256: owned.get(path), byteIdentical: true });
  }
  const generated = locales.map((locale) => {
    const path = `frontend/src/i18n/resources/business/${locale}.ts`;
    requireRegular(root, path);
    requireRegular(candidate, path);
    if (!report.generatedFiles.includes(path)) throw new Error(`Not declared generated by official report: ${path}`);
    return { locale, path, originalBytes: read(root, path), candidateBytes: read(candidate, path) };
  });
  // Back up every original, as exact raw bytes, before performing any copy.
  mkdirSync(join(evidence, 'originals'), { recursive: true });
  for (const row of generated) {
    const originalPath = join(evidence, 'originals', `${row.locale}.ts`);
    writeFileSync(originalPath, row.originalBytes, { flag: 'wx' });
    if (!readFileSync(originalPath).equals(row.originalBytes)) throw new Error(`Raw original backup mismatch: ${row.path}`);
    receipt.originals.push({ path: row.path, backupPath: originalPath, bytes: row.originalBytes.length, sha256: sha256(row.originalBytes) });
  }
  for (const row of generated) {
    // A copy never regenerates or edits the output; it uses official bytes.
    if (!read(root, row.path).equals(row.originalBytes)) throw new Error(`Live generated file changed before copy: ${row.path}`);
    if (!read(candidate, row.path).equals(row.candidateBytes)) throw new Error(`Official generated file changed before copy: ${row.path}`);
    copyFileSync(resolve(candidate, row.path), resolve(root, row.path));
    const after = read(root, row.path);
    if (!after.equals(row.candidateBytes)) throw new Error(`Generated copy mismatch: ${row.path}`);
    receipt.copies.push({ path: row.path, source: resolve(candidate, row.path), destination: resolve(root, row.path), copiedUTC: new Date().toISOString(), beforeSHA256: sha256(row.originalBytes), sourceSHA256: sha256(row.candidateBytes), afterSHA256: sha256(after), bytes: after.length, byteIdentical: true });
  }
  if (JSON.stringify(canonicalPaths(root)) !== JSON.stringify(livePaths) || JSON.stringify(canonicalPaths(candidate)) !== JSON.stringify(candidatePaths)) throw new Error('Canonical inventory changed during refresh');
  for (const row of receipt.canonicalBefore) {
    const liveBytes = read(root, row.path), candidateBytes = read(candidate, row.path);
    const liveHash = sha256(liveBytes), candidateHash = sha256(candidateBytes);
    if (!liveBytes.equals(candidateBytes) || liveHash !== row.liveSHA256 || candidateHash !== row.candidateSHA256) throw new Error(`Canonical source changed during refresh: ${row.path}`);
    receipt.canonicalAfter.push({ path: row.path, liveSHA256: liveHash, candidateSHA256: candidateHash, byteIdentical: true, unchanged: true });
  }
  for (const row of receipt.copies) {
    if (sha256(read(root, row.path)) !== row.afterSHA256 || !read(root, row.path).equals(read(candidate, row.path))) throw new Error(`Generated source changed after refresh: ${row.path}`);
  }
  receipt.status = 'passed';
  receipt.sourceFreezeUTC = new Date().toISOString();
} catch (error) {
  receipt.status = 'failed';
  receipt.error = { name: error.name, message: error.message };
  process.exitCode = 1;
} finally {
  receipt.finishedUTC = new Date().toISOString();
  writeFileSync(join(evidence, 'copy-receipt.json'), `${JSON.stringify(receipt, null, 2)}\n`, { flag: 'wx' });
  console.log(JSON.stringify({ status: receipt.status, canonicalBefore: receipt.canonicalBefore.length, canonicalAfter: receipt.canonicalAfter.length, rawOriginals: receipt.originals.length, generatedCopies: receipt.copies.length, sourceFreezeUTC: receipt.sourceFreezeUTC, error: receipt.error }));
}
