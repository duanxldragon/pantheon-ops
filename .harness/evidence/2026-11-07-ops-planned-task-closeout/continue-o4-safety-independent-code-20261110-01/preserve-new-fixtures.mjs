import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const evidence = path.dirname(fileURLToPath(import.meta.url));
const workspace = process.cwd();
const temp = path.join(workspace,'.tmp'); fs.mkdirSync(temp,{recursive:true});
const root = fs.mkdtempSync(path.join(temp,'continue-o4-safety-independent-code-'));
os.tmpdir = () => root;
fs.appendFileSync(path.join(evidence,'fixture-roots.jsonl'),JSON.stringify({root,pid:process.pid})+'\n');
const n=Number(process.env.GIT_CONFIG_COUNT??0); process.env.GIT_CONFIG_COUNT=String(n+1);
process.env[`GIT_CONFIG_KEY_${n}`]='core.longpaths'; process.env[`GIT_CONFIG_VALUE_${n}`]='true';
process.env.GOPROXY='off'; process.env.GOSUMDB='off'; process.env.GOTOOLCHAIN='local';
const nativeRm=fs.rmSync;
fs.rmSync=function(target,options){
 if(!options?.recursive) return nativeRm.call(this,target,options);
 const absolute=path.resolve(target);
 if(!absolute.startsWith(root+path.sep)) throw new Error('Review teardown outside NEW fixture root refused');
 if(!fs.existsSync(absolute)||path.dirname(absolute)===root) return;
 const stat=fs.lstatSync(absolute,{bigint:true});
 if(!stat.isDirectory()||stat.isSymbolicLink()) throw new Error('Review retained rename requires real directory');
 const retained=absolute+'.retained-'+crypto.randomUUID();
 if(!retained.startsWith(root+path.sep)) throw new Error('Review retained rename outside fixture root');
 const current=fs.lstatSync(absolute,{bigint:true});
 if(current.dev!==stat.dev||current.ino!==stat.ino) throw new Error('Review fixture identity changed');
 fs.renameSync(absolute,retained);
 fs.appendFileSync(path.join(evidence,'retained-moves.jsonl'),JSON.stringify({absolute,retained,dev:String(stat.dev),ino:String(stat.ino)})+'\n');
};