const businessTelemetryKey = "pantheon_business_telemetry"

// BusinessTelemetryMiddleware runs after RequestContextMiddleware and before
// any body/CSRF/rate/auth denial. Gin has already selected FullPath here. The
// startup registry selects the strategy before capture; no client header does.
// otelgin v0.69 cannot disable automatic URL/UA attributes or raw c.Errors, so
// opted routes use a small adapter with the same global tracer provider.
func BusinessTelemetryMiddleware() gin.HandlerFunc {
	tracer := otel.GetTracerProvider().Tracer(otelgin.ScopeName, trace.WithInstrumentationVersion(otelgin.Version))
	return func(c *gin.Context) {
		route, protected := auditpolicy.Match(c)
		if !protected {
			c.Next()
			return
		}
		c.Set(businessTelemetryKey, true)
		requestID := common.GetRequestID(c) // generated by the preceding opted request-context branch
		savedCtx := c.Request.Context()
		// Incoming trace IDs, tracestate and baggage are client-controlled too.
		// Keep cancellation/deadlines and server values; propagate this new server
		// trace downstream through the existing global propagators, without extraction.
		ctx := baggage.ContextWithBaggage(savedCtx, baggage.Baggage{})
		ctx, span := tracer.Start(ctx, auditpolicy.ActionName(route), trace.WithNewRoot(), trace.WithSpanKind(trace.SpanKindServer),
			trace.WithAttributes(attribute.String("http.request.method", route.Method), attribute.String("http.route", route.Template),
				attribute.String("business.action", auditpolicy.ActionName(route)), attribute.String("request.id", requestID)))
		c.Request = c.Request.WithContext(ctx)
		defer finishBusinessTelemetry(savedCtx, c, span)
		c.Next()
	}
}

// Inspect only the presence of a panic/error, never its value/string.
// Finalize before rethrowing to the existing metadata-aware recovery.
func finishBusinessTelemetry(savedCtx context.Context, c *gin.Context, span trace.Span) {
	panicked := recover()
	metadata := auditpolicy.Metadata(c)
	if panicked != nil {
		metadata.Outcome = auditpolicy.OutcomeUnknown
		c.AbortWithStatus(http.StatusInternalServerError)
		span.AddEvent("business.request.panic")
	}
	if len(c.Errors) > 0 {
		span.AddEvent("business.request.error")
		if metadata.Outcome == auditpolicy.OutcomeSuccess {
			metadata.Outcome = auditpolicy.OutcomeUnknown
		}
	}
	if savedCtx.Err() != nil {
		metadata.Outcome = auditpolicy.OutcomeUnknown
	}
	span.SetAttributes(businessTelemetryAttributes(c, metadata)...)
	span.SetStatus(businessTelemetryStatus(savedCtx, c, metadata, panicked), "")
	span.End()
	c.Request = c.Request.WithContext(savedCtx)
	if panicked != nil {
		panic(panicked)
	}
}

func businessTelemetryAttributes(c *gin.Context, metadata auditpolicy.SafeMetadata) []attribute.KeyValue {
	return []attribute.KeyValue{
		attribute.Int("http.response.status_code", c.Writer.Status()),
		attribute.String("business.outcome", auditpolicy.OutcomeName(metadata.Outcome)),
		attribute.Int64("business.actor_id", businessTelemetryID(metadata.ActorID)),
		attribute.Int64("business.tenant_id", businessTelemetryID(metadata.TenantID)),
		attribute.Int64("business.datasource_id", businessTelemetryID(metadata.DatasourceID)),
		attribute.Int64("business.history_id", businessTelemetryID(metadata.HistoryID)),
		attribute.Int64("business.view_id", businessTelemetryID(metadata.ViewID)),
		attribute.Int64("business.count", int64(metadata.Count)),
		attribute.Int64("business.catalog_version", int64(metadata.CatalogVersion)),
	}
}

func businessTelemetryStatus(savedCtx context.Context, c *gin.Context, metadata auditpolicy.SafeMetadata, panicked any) codes.Code {
	if metadata.Outcome == auditpolicy.OutcomeSuccess && c.Writer.Status() < 400 && !c.IsAborted() && panicked == nil && len(c.Errors) == 0 && savedCtx.Err() == nil {
		return codes.Ok
	}
	return codes.Error
}

// LegacyTelemetryMiddleware stays at the original otelgin position. The frozen
// server flag prevents a later request mutation from re-enabling raw capture.
// Everything else retains otelgin's provider, propagators and capture defaults.
func LegacyTelemetryMiddleware(service string) gin.HandlerFunc {
	return otelgin.Middleware(service, otelgin.WithGinFilter(func(c *gin.Context) bool {
		_, protected := auditpolicy.Match(c)
		return !protected && !c.GetBool(businessTelemetryKey)
	}))
}

func businessTelemetryID(id uint64) int64 {
	if id > math.MaxInt64 {
		return 0
	}
	return int64(id)
}
