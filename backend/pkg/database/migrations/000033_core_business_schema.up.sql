-- Ops core business schema baseline. The official Base runner assembles this
-- consumer-owned migration before business routes/workers are registered.
-- Current model definitions were inspected in an isolated MySQL 8 schema.
-- CREATE IF NOT EXISTS preserves existing tables and data; this baseline
-- fills missing tables and does not claim to upgrade incompatible legacy columns.
-- Active-row keys enforce active natural-key uniqueness; nullable deleted_at alone does not.
-- Existing incompatible tables/indexes require a separate reviewed upgrade migration.
-- Host state_version defaults to 1, including when migration 000032 skipped a missing table.

